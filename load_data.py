"""
load_data.py — Unified data loader for the business failure prediction model.

PURPOSE
    Load a labelled financial distress dataset from one of two sources:
    1. Kaggle "Financial Distress" dataset (preferred — real panel data)
       https://www.kaggle.com/datasets/shebrahimi/financial-distress
    2. Synthetic dataset generated by generate_data.py (fallback)

    The caller (model.py) does not need to know which source is used.
    This module returns a DataFrame with a guaranteed schema:
        columns: the 7 Altman-style ratio features + the `failed` target
        dtype:   numeric features, integer target (0/1)

COLUMN MAPPING (Kaggle -> Altman-style)
    The Kaggle dataset uses generic x1..x83 columns that are undocumented.
    Standard practice in the literature and Kaggle notebooks maps the
    first few columns to Altman-style ratios as follows:

        x1  -> Working capital / Total assets       -> working_capital_ratio
        x2  -> Retained earnings / Total assets     -> retained_earnings_ratio
        x3  -> EBIT / Total assets                  -> ebit_ratio
        x4  -> Sales / Total assets                 -> revenue_ratio
        x5  -> Market-value equity / Book-value debt -> (debt_equity_ratio inverted;
                                                         stored as 1/x5 with floor)
        x6  -> Net income / Total assets            -> net_income_ratio
        x7  -> Current assets / Current liabilities -> current_ratio

    This mapping is an approximation — the dataset authors never published
    the exact feature dictionary. The code below states this explicitly.
    The mapping is applied with data validation that FAILS LOUDLY if the
    Kaggle columns are not present or out of range.

TARGET MAPPING (Kaggle -> binary failed/healthy)
    The Kaggle dataset has a continuous "Financial Distress" column. The
    standard convention, established in the original Campbell/Hilscher/Szilagyi
    literature and used in most published Kaggle notebooks, is:

        failed = 1 if Financial Distress < -0.50  (severe distress)
        failed = 0 otherwise                       (healthy or mild distress)

    This threshold is defensible but not unique. Alternative thresholds
    (0, -0.25) produce different class balance. We use -0.50 and document it.

USAGE
    from load_data import load_financial_distress_data
    df = load_financial_distress_data()  # prefers Kaggle, falls back to synthetic
"""

import os
import pandas as pd
import numpy as np

# ── Expected schema that model.py depends on ────────────────────────────────
REQUIRED_FEATURES = [
    "working_capital_ratio",
    "retained_earnings_ratio",
    "ebit_ratio",
    "debt_equity_ratio",
    "revenue_ratio",
    "current_ratio",
    "net_income_ratio",
]
REQUIRED_TARGET = "failed"

# ── Kaggle source specifics ─────────────────────────────────────────────────
KAGGLE_FILENAMES = [
    "Financial Distress.csv",           # original filename from Kaggle zip
    "financial_distress.csv",           # common rename
    "financial-distress.csv",
]
KAGGLE_DISTRESS_THRESHOLD = -0.50       # "failed" if Financial Distress < this

KAGGLE_COLUMN_MAP = {
    # Kaggle col -> our col. Comment explains the approximation.
    "x1": "working_capital_ratio",      # Working capital / Total assets
    "x2": "retained_earnings_ratio",    # Retained earnings / Total assets
    "x3": "ebit_ratio",                 # EBIT / Total assets
    "x4": "revenue_ratio",              # Sales / Total assets
    # x5 is inverted (book-debt / market-equity) — see below
    "x6": "net_income_ratio",           # Net income / Total assets
    "x7": "current_ratio",              # Current assets / Current liabilities
}

# ── Paths ───────────────────────────────────────────────────────────────────
HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(HERE, "data")
SYNTHETIC_PATH = os.path.join(DATA_DIR, "financial_distress_data.csv")


# ══════════════════════════════════════════════════════════════════════════
# PUBLIC LOADER
# ══════════════════════════════════════════════════════════════════════════
def load_financial_distress_data(source: str = "auto") -> tuple[pd.DataFrame, str]:
    """
    Load labelled financial distress data.

    Args:
        source: "auto" (default), "kaggle", or "synthetic".
                "auto" prefers Kaggle if found, falls back to synthetic.

    Returns:
        (df, source_used) — DataFrame with the REQUIRED_FEATURES + REQUIRED_TARGET
        columns, and a string indicating which source was actually loaded.

    Raises:
        FileNotFoundError: if `source="kaggle"` and no Kaggle file is present.
        ValueError: if the loaded data fails schema validation.
    """
    os.makedirs(DATA_DIR, exist_ok=True)

    if source == "kaggle":
        return _load_kaggle(required=True), "kaggle"
    if source == "synthetic":
        return _load_synthetic(), "synthetic"

    # auto mode
    kaggle_df = _load_kaggle(required=False)
    if kaggle_df is not None:
        print("  -> Using Kaggle Financial Distress dataset")
        return kaggle_df, "kaggle"

    print("  -> Kaggle dataset not found in data/ — falling back to synthetic")
    print("    To upgrade: download from")
    print("    https://www.kaggle.com/datasets/shebrahimi/financial-distress")
    print("    and place 'Financial Distress.csv' in data/")
    return _load_synthetic(), "synthetic"


# ══════════════════════════════════════════════════════════════════════════
# KAGGLE LOADER
# ══════════════════════════════════════════════════════════════════════════
def _load_kaggle(required: bool = False) -> pd.DataFrame | None:
    """Load and transform the Kaggle Financial Distress dataset.

    Returns None if the file is not present and `required=False`.
    Raises FileNotFoundError if required=True and not found.
    Raises ValueError if the file is present but does not contain
    the expected columns (loud failure — not silent).
    """
    kaggle_path = None
    for fn in KAGGLE_FILENAMES:
        candidate = os.path.join(DATA_DIR, fn)
        if os.path.exists(candidate):
            kaggle_path = candidate
            break

    if kaggle_path is None:
        if required:
            raise FileNotFoundError(
                f"Kaggle Financial Distress dataset not found in {DATA_DIR}. "
                f"Download from https://www.kaggle.com/datasets/shebrahimi/financial-distress "
                f"and place 'Financial Distress.csv' in data/."
            )
        return None

    print(f"  -> Loading Kaggle file: {os.path.basename(kaggle_path)}")
    raw = pd.read_csv(kaggle_path)

    # ── Validate schema ─────────────────────────────────────────────────────
    expected_target = "Financial Distress"
    expected_features = list(KAGGLE_COLUMN_MAP.keys()) + ["x5"]  # x5 inverted
    missing = [c for c in expected_features if c not in raw.columns]
    if expected_target not in raw.columns:
        missing.insert(0, expected_target)
    if missing:
        raise ValueError(
            f"Kaggle file is missing expected columns: {missing}. "
            f"Got columns: {list(raw.columns)[:15]}... "
            f"This loader expects the original Kaggle schema with columns "
            f"x1..x83 and 'Financial Distress'. If the dataset has been "
            f"renamed or restructured, update KAGGLE_COLUMN_MAP in load_data.py."
        )

    # ── Transform ───────────────────────────────────────────────────────────
    df = pd.DataFrame()

    # Direct column mappings
    for k_col, our_col in KAGGLE_COLUMN_MAP.items():
        df[our_col] = pd.to_numeric(raw[k_col], errors="coerce")

    # x5 is Market equity / Book debt — invert to our debt_equity_ratio
    # with a floor to avoid division by zero.
    x5 = pd.to_numeric(raw["x5"], errors="coerce")
    df["debt_equity_ratio"] = 1.0 / x5.clip(lower=0.01)

    # Binary target from continuous distress score
    distress = pd.to_numeric(raw[expected_target], errors="coerce")
    df["failed"] = (distress < KAGGLE_DISTRESS_THRESHOLD).astype(int)

    # Drop rows with missing values after coercion
    before = len(df)
    df = df.dropna(subset=REQUIRED_FEATURES).reset_index(drop=True)
    dropped = before - len(df)
    if dropped > 0:
        print(f"  -> Dropped {dropped} rows with missing/non-numeric features")

    # ── Sanity-check the result ─────────────────────────────────────────────
    _validate_schema(df, source_name="Kaggle")
    print(f"  -> Kaggle data loaded: {len(df)} company-years "
          f"({df[REQUIRED_TARGET].sum()} failed, "
          f"{(df[REQUIRED_TARGET] == 0).sum()} healthy)")
    return df


# ══════════════════════════════════════════════════════════════════════════
# SYNTHETIC LOADER
# ══════════════════════════════════════════════════════════════════════════
def _load_synthetic() -> pd.DataFrame:
    """Load the synthetic dataset produced by generate_data.py."""
    if not os.path.exists(SYNTHETIC_PATH):
        raise FileNotFoundError(
            f"Synthetic dataset not found at {SYNTHETIC_PATH}. "
            f"Run `python generate_data.py` first."
        )
    df = pd.read_csv(SYNTHETIC_PATH)
    _validate_schema(df, source_name="Synthetic")
    print(f"  -> Synthetic data loaded: {len(df)} companies "
          f"({df[REQUIRED_TARGET].sum()} failed, "
          f"{(df[REQUIRED_TARGET] == 0).sum()} healthy)")
    return df


# ══════════════════════════════════════════════════════════════════════════
# SCHEMA VALIDATION — fails LOUDLY if anything is off
# ══════════════════════════════════════════════════════════════════════════
def _validate_schema(df: pd.DataFrame, source_name: str) -> None:
    """Raise ValueError with a clear message if the DataFrame is malformed."""
    missing_feats = [c for c in REQUIRED_FEATURES if c not in df.columns]
    if missing_feats:
        raise ValueError(
            f"{source_name} data is missing required feature columns: {missing_feats}. "
            f"Expected: {REQUIRED_FEATURES}. Got: {list(df.columns)}"
        )
    if REQUIRED_TARGET not in df.columns:
        raise ValueError(
            f"{source_name} data is missing target column '{REQUIRED_TARGET}'. "
            f"Got columns: {list(df.columns)}"
        )
    if not set(df[REQUIRED_TARGET].unique()).issubset({0, 1}):
        raise ValueError(
            f"{source_name} target '{REQUIRED_TARGET}' contains non-binary values: "
            f"{sorted(df[REQUIRED_TARGET].unique())}"
        )
    if len(df) < 50:
        raise ValueError(
            f"{source_name} data has only {len(df)} rows — too small to train. "
            f"Minimum 50 required."
        )
    for f in REQUIRED_FEATURES:
        if df[f].isna().any():
            raise ValueError(
                f"{source_name} feature '{f}' contains NaN values. "
                f"Clean the data before loading."
            )


if __name__ == "__main__":
    df, src = load_financial_distress_data(source="auto")
    print(f"\nLoaded from: {src}")
    print(f"Shape: {df.shape}")
    print(f"Class balance: {df[REQUIRED_TARGET].value_counts().to_dict()}")
    print(f"\nFirst 3 rows:")
    print(df.head(3))
